#!/usr/bin/env python3
"""Dependency-free, idempotent Klipper Revive install/uninstall.

Only managed includes, managed config snippets and our own symlink are touched.
A running print is never restarted. Manual installations are not overwritten.
"""
import argparse
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile
from urllib.request import urlopen

ORIGIN = "https://github.com/sezgynus/klipper-revive.git"
MARKER = "# Managed by Klipper Revive. Do not edit this file.\n"
KLIPPER_NAME = "klipper_revive.cfg"
MOONRAKER_NAME = "klipper_revive_update.cfg"
EXTRA_NAME = "klipper_revive.py"
EXTRA_MODULES = (EXTRA_NAME, "klipper_revive_store.py", "klipper_revive_collect.py", "klipper_revive_recovery.py")


def error(message):
    raise RuntimeError(message)


def file_text(path):
    return path.read_text(encoding="utf-8")


def atomic_write(path, content):
    """Preserve a one-time original backup when modifying an existing file."""
    if path.is_file() and file_text(path) == content:
        return False
    if path.exists():
        backup = path.with_name(path.name + ".klipper-revive.bak")
        if not backup.exists():
            shutil.copy2(path, backup)
    fd, name = tempfile.mkstemp(prefix=".revive-", dir=str(path.parent))
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as stream:
            stream.write(content)
        if path.exists():
            os.chmod(name, path.stat().st_mode & 0o777)
        else:
            os.chmod(name, 0o644)
        os.replace(name, path)
    finally:
        if os.path.exists(name):
            os.unlink(name)
    return True


def include_line(name):
    return "[include " + name + "]"


def add_include(content, name):
    line = include_line(name)
    lines = content.splitlines(keepends=True)
    if name != KLIPPER_NAME:
        if any(item.strip() == line for item in lines):
            return content
        return content.rstrip("\n") + "\n\n" + line + "\n"

    # Klipper's SAVE_CONFIG parser requires that *all* lines after its
    # autogenerated header start with '#*#'. Appending our include below
    # that header makes Klipper discard saved probe z_offset/mesh values.
    # Preserve the original saved block verbatim and install before it.
    markers = [i for i, item in enumerate(lines)
               if item.startswith("#*# <") and "SAVE_CONFIG" in item]
    if len(markers) > 1:
        error("Multiple SAVE_CONFIG headers detected; refusing to edit config")
    if not markers:
        if any(item.strip() == line for item in lines):
            return content
        return content.rstrip("\n") + "\n\n" + line + "\n"

    marker = markers[0]
    existing = [i for i, item in enumerate(lines) if item.strip() == line]
    if len(existing) == 1 and existing[0] < marker:
        return content
    # Repair prior installer versions that placed the include *after*
    # SAVE_CONFIG; ensure only one include remains in the normal region.
    prefix = "".join(item for i, item in enumerate(lines[:marker])
                     if i not in existing)
    suffix = "".join(item for i, item in enumerate(lines[marker:], marker)
                     if i not in existing)
    return prefix.rstrip("\n") + "\n\n" + line + "\n\n" + suffix


def remove_include(content, name):
    line = include_line(name)
    lines = content.splitlines(keepends=True)
    return "".join(item for item in lines if item.strip() != line)


def managed_content(path, expected):
    if path.is_symlink():
        error("Refusing to overwrite a symlink: " + str(path))
    if path.exists() and not path.is_file():
        error("Not a regular file: " + str(path))
    if path.exists():
        current = file_text(path)
        if current != expected and not current.startswith(MARKER):
            error("Refusing to overwrite unmanaged configuration: " + str(path))


def updater_text(repo):
    return (
        MARKER
        + "[update_manager klipper-revive]\n"
        + "type: git_repo\n"
        + "channel: dev\n"
        + "path: " + str(repo) + "\n"
        + "origin: " + ORIGIN + "\n"
        + "primary_branch: master\n"
        + "managed_services: klipper\n"
    )


def printer_text():
    return MARKER + "[klipper_revive]\n"


def paths(args):
    home = Path.home()
    repo = Path(__file__).resolve().parent.parent
    klipper = Path(args.klipper_dir or home / "klipper").expanduser().resolve()
    data = Path(args.printer_data_dir or home / "printer_data").expanduser().resolve()
    return {
        "repo": repo,
        "source": repo / "klipper_extras" / EXTRA_NAME,
        "extra": klipper / "klippy" / "extras" / EXTRA_NAME,
        "printer": Path(args.printer_config or data / "config" / "printer.cfg").expanduser().resolve(),
        "moonraker": Path(args.moonraker_config or data / "config" / "moonraker.conf").expanduser().resolve(),
    }


def module_links(p):
    return [(p["source"].parent / name, p["extra"].parent / name)
            for name in EXTRA_MODULES]


def validate(p, installing):
    for source, destination in module_links(p):
        if not source.is_file():
            error("Klipper Revive source module missing: " + str(source))
    for field in ("printer", "moonraker"):
        if not p[field].is_file():
            error("Configuration not found: " + str(p[field]))
        if p[field].is_symlink():
            error("Refusing to edit symlinked main configuration: " + str(p[field]))
    if not p["extra"].parent.is_dir():
        error("Klipper extras directory not found: " + str(p["extra"].parent))
    for source, destination in module_links(p):
        if destination.is_symlink():
            if destination.resolve() != source.resolve():
                error("Foreign symlink occupies: " + str(destination))
        elif destination.exists():
            error("Refusing to replace existing module: " + str(destination))
    if installing:
        managed_content(p["printer"].parent / KLIPPER_NAME, printer_text())
        managed_content(p["moonraker"].parent / MOONRAKER_NAME, updater_text(p["repo"]))


def install(p):
    validate(p, True)
    changed = False
    for source, destination in module_links(p):
        if not destination.is_symlink():
            destination.symlink_to(source)
            print("Linked Klipper extra:", destination)
            changed = True
    for field, name, content in (
        ("printer", KLIPPER_NAME, printer_text()),
        ("moonraker", MOONRAKER_NAME, updater_text(p["repo"])),
    ):
        conf = p[field]
        snippet = conf.parent / name
        changed |= atomic_write(snippet, content)
        changed |= atomic_write(conf, add_include(file_text(conf), name))
    print("Klipper Revive installed. Moonraker update entry: klipper-revive")
    return changed


def uninstall(p):
    validate(p, False)
    changed = False
    for field, name in (("printer", KLIPPER_NAME), ("moonraker", MOONRAKER_NAME)):
        conf = p[field]
        snippet = conf.parent / name
        if snippet.exists():
            if snippet.is_symlink() or not snippet.is_file() or not file_text(snippet).startswith(MARKER):
                error("Refusing to remove unmanaged configuration: " + str(snippet))
        current = file_text(conf)
        new = remove_include(current, name)
        changed |= atomic_write(conf, new)
        if snippet.exists():
            snippet.unlink()
            changed = True
    for source, destination in module_links(p):
        if destination.is_symlink() and destination.resolve() == source.resolve():
            destination.unlink()
            changed = True
    print("Klipper Revive configuration and symlink removed; repository preserved.")
    return changed


def idle_from_moonraker(url):
    """Confirm that reloading the host cannot interrupt an active print.

    /server/info remains available when Klippy cannot load its configuration;
    print_stats is unavailable in that state. Treat a startup config error as
    safe to restart, but NEVER infer safety from a disconnected / starting host
    or an emergency shutdown. Those states require operator confirmation.
    """
    base = url.rstrip("/")
    try:
        with urlopen(base + "/server/info", timeout=2) as response:
            info = json.load(response)["result"]
        state = info["klippy_state"]
        if state == "error":
            return True, "Klipper configuration/startup error"
        if state != "ready":
            return False, "Klipper state: " + str(state)
        with urlopen(base + "/printer/objects/query?print_stats", timeout=2) as response:
            data = json.load(response)
        print_state = data["result"]["status"]["print_stats"]["state"]
    except (OSError, ValueError, KeyError, TypeError) as exc:
        return False, "printer state unavailable (" + str(exc) + ")"
    if print_state in ("standby", "complete", "cancelled", "error"):
        return True, "print_stats: " + print_state
    return False, "print_stats: " + str(print_state)


def authorize_service_restart():
    """Authenticate once, using the controlling SSH terminal when available.

    In `curl ... | bash` installations stdin is a pipe, but /dev/tty
    remains usable for the sudo password prompt. Never use sudo -S or
    consume bytes from the downloaded shell script's stdin.
    """
    if shutil.which("sudo") is None or shutil.which("systemctl") is None:
        error("Automatic restart requires sudo and systemctl. "
              "Install these tools or run with --no-restart.")

    # Quietly handle the common case where sudo credentials are cached
    # or the installer user has passwordless sudo.
    authorized = subprocess.run(
        ["sudo", "-n", "-v"], check=False,
        stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    if authorized.returncode == 0:
        return

    # Standard input may contain the piped installer itself, not a TTY.
    # /dev/tty is the *controlling* terminal, independent of stdin.
    try:
        terminal = open("/dev/tty", "r+")
    except OSError:
        error("sudo authentication is required but no interactive terminal "
              "is available. Run the installer/uninstaller in an SSH "
              "terminal, or use --no-restart and restart both services "
              "manually when the printer is idle.")

    with terminal:
        print("Administrator permission is needed to restart Klipper and "
              "Moonraker. Enter your sudo password in the terminal.",
              flush=True)
        authorized = subprocess.run(
            ["sudo", "-v"], stdin=terminal, stdout=terminal,
            stderr=terminal, check=False)
    if authorized.returncode:
        error("sudo authentication failed; configuration changes were "
              "saved, but services were not restarted.")


def restart_if_safe(args, changed, action="install"):
    # Even a repeated uninstall may need to unload an already-unlinked
    # Python module from the live Klipper process.
    needs_restart = changed or action == "uninstall"
    if not needs_restart:
        print("No changes; no restart needed.")
        return
    if args.no_restart:
        print("Restart deferred by --no-restart. Service processes must "
              "be restarted when the printer is idle to apply changes.")
        return

    idle, state = idle_from_moonraker(args.moonraker_url)
    if not idle:
        print("Service restart deferred: " + state + ".")
        print("Changes were saved, but running Klipper/Moonraker processes "
              "will not reflect them until restarted.")
        print("After verifying the printer is not printing or paused, run: "
              "sudo systemctl restart " + args.klipper_service + " "
              + args.moonraker_service)
        return

    authorize_service_restart()

    # Authentication can take time; check again before service changes.
    # Do not recheck between Klipper and Moonraker restart because Klipper
    # temporarily disconnects while the first restart is in progress.
    idle, state = idle_from_moonraker(args.moonraker_url)
    if not idle:
        print("Service restart deferred: printer state changed while "
              "awaiting authorization (" + state + ").")
        return

    for service in (args.klipper_service, args.moonraker_service):
        result = subprocess.run(
            ["sudo", "-n", "systemctl", "restart", service], check=False)
        if result.returncode:
            error("Could not restart " + service + " (exit "
                  + str(result.returncode) + "). Configuration changes "
                  "were saved; verify the service status before continuing.")
        print("Restarted", service)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("action", choices=("install", "uninstall"))
    parser.add_argument("--klipper-dir", help="Klipper checkout directory")
    parser.add_argument("--printer-data-dir", help="Moonraker printer_data directory")
    parser.add_argument("--printer-config", help="Override printer.cfg path")
    parser.add_argument("--moonraker-config", help="Override moonraker.conf path")
    parser.add_argument("--moonraker-url", default="http://127.0.0.1:7125")
    parser.add_argument("--klipper-service", default="klipper")
    parser.add_argument("--moonraker-service", default="moonraker")
    parser.add_argument("--no-restart", action="store_true", help="Do not restart services")
    args = parser.parse_args()
    if os.geteuid() == 0:
        error("Run as the normal printer user, not root")
    p = paths(args)
    changed = install(p) if args.action == "install" else uninstall(p)
    restart_if_safe(args, changed, action=args.action)


if __name__ == "__main__":
    try:
        main()
    except (OSError, RuntimeError) as exc:
        print("ERROR:", exc, file=sys.stderr)
        sys.exit(1)
